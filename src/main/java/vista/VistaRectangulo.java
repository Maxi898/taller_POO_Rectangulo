    private void btnVerificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerificarActionPerformed
if (!controlador.hayRectangulo()) {
    txtResultado.setText("Primero crea el rectángulo.");
    return;
}
double px = Double.parseDouble(txtPuntoX.getText());
double py = Double.parseDouble(txtPuntoY.getText());
if (controlador.puntoDentro(px, py)) {
    txtResultado.setText("El punto (" + px + ", " + py + ") SÍ está dentro del rectángulo.");
} else {
    txtResultado.setText("El punto (" + px + ", " + py + ") NO está dentro del rectángulo.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnVerificarActionPerformed

