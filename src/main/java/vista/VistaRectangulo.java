    private void btnEscalarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEscalarActionPerformed
if (!controlador.hayRectangulo()) {
    txtResultado.setText("Primero crea el rectángulo.");
    return;
}
double factor = Double.parseDouble(txtFactor.getText());
if (controlador.escalar(factor)) {
    txtResultado.setText("Rectángulo escalado:\n" + controlador.getInformacion()
            + "\nNueva área: " + controlador.calcularArea());
} else {
    txtResultado.setText("El factor debe ser mayor que 0.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEscalarActionPerformed

